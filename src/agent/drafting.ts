export interface Problem {
  readonly quote: string
  readonly rule: string
  readonly fix: string
}

/** 空白を無視して比べる。読み手は本文を写すときに改行と字下げを揃え直すことがある。 */
const bare = (s: string): string => s.replace(/\s/g, "")

/**
 * 本文に実在する引用だけを位置付きの指摘として返す。
 * 引用が一致しない指摘は reviewOutcome が引用位置を伏せ、規則と修正案だけを残す。
 */
export function keepQuoted(problems: readonly Problem[] | undefined, title: string, body: string): Problem[] {
  const src = bare(`${title}\n${body}`)
  return (problems ?? []).filter((p) => p.quote.trim() !== "" && src.includes(bare(p.quote)))
}

/** 精査役の返り。読めない形で返ることがあるので、全部の欄を任意にしてある。 */
export interface Review {
  readonly verdict?: string
  readonly problems?: readonly Problem[]
}

/**
 * 精査の返りを、出すか出さないかの判定に変換する。「出す」と言われたときだけ出す。
 *
 * 前は「直す」と言われ、かつ引用が本文に当たった指摘が1件以上あるときだけ止めていた。
 * 裏を返すと、返りが読めなかった回と、「直す」と言いながら引用を写せなかった回が
 * どちらも投稿されていた。精査役が応答しなかった回は、指摘が無い回と区別されず投稿される。
 *
 * 引用が当たらなかった指摘も捨てない。落とすのは引用だけで、規律と直し方は書いた側が使える。
 */
export function reviewOutcome(
  review: Review | undefined,
  title: string,
  body: string,
): { readonly post: true } | { readonly post: false; readonly text: string } {
  if (review?.verdict === "出す") return { post: true }
  const shown = keepQuoted(review?.problems, title, body)
  const rest = (review?.problems ?? []).filter((p) => !shown.includes(p))
  const lines = [
    ...shown.map((p) => `- 「${p.quote}」\n  ${p.rule}\n  → ${p.fix}`),
    ...rest.map((p) => `- (引用が本文と一致しなかった)\n  ${p.rule}\n  → ${p.fix}`),
  ]
  if (lines.length === 0) {
    return {
      post: false,
      text:
        `出していない。**精査役の返りが読めなかった**(判定: ${review?.verdict ?? "返らなかった"})。\n` +
        "本文は捨てずに、次の回でもう一度呼ぶ。",
    }
  }
  return {
    post: false,
    text:
      `出していない。**読み手に止められた。**\n${lines.join("\n")}\n` +
      "直してから、もう一度呼ぶ。**書き足して答えない** — 指摘された文は落とすか書き換える。",
  }
}

/**
 * 非公開の確定値が本文にそのまま漏れていないかを見る。
 *
 * 誤検出しないものだけを止める。疑わしいものまで弾くと一度も出せなくなり、
 * 出せない仕組みは外されて、そのとき一緒にこの検査も消える。見るのは2つだけ:
 *   - 非公開の確定値に書かれている連絡先そのもの(メール・電話・URL)
 *   - 非公開の確定値と ${MIN_SHARED} 文字以上そのまま一致する断片
 * 日本語で ${MIN_SHARED} 文字が偶然一致することはほぼ無い。逆に「歯科医院」程度の
 * 一般語は当たらない — そこは規律の側に任せる。
 */
export function findLeaks(body: string, secrets: readonly string[]): string[] {
  const hit = new Set<string>()
  for (const s of secrets) {
    for (const re of CONTACT) {
      for (const m of s.matchAll(re)) if (body.includes(m[0])) hit.add(m[0])
    }
    // 当たった窓は隣と重なる。繋いで一番長いところだけ返す — 断片を並べて突き返すと、
    // 書き直す側はどこを消せばいいのか分からない。
    let i = 0
    while (i + MIN_SHARED <= s.length) {
      if (!body.includes(s.slice(i, i + MIN_SHARED))) {
        i++
        continue
      }
      let end = i + MIN_SHARED
      while (end < s.length && body.includes(s.slice(i, end + 1))) end++
      hit.add(s.slice(i, end))
      i = end - MIN_SHARED + 2
    }
  }
  // 長いものに含まれる短いものは落とす(連絡先と地の文の一致が二重に出る)。
  const all = [...hit]
  return all.filter((a) => !all.some((b) => b !== a && b.includes(a)))
}

/**
 * 「課題：」「実験：」のように、見出しの頭に役割ラベルを置く形。中身の側はラベルの後ろに退く。
 * 数字始まりと `//` 続きは外す — 時刻(18:00)と URL をラベルと読み違えるため。
 */
const LABELLED_HEAD = /^[^\s:：#0-9０-９]{1,6}[：:](?!\/)/

/** 見出し行の中身。`#` の数は問わない。 */
const HEAD_LINE = /^\s{0,3}#{1,6}\s+(.+?)\s*$/gm

/**
 * 中身ではなく並べ方のほうを見る。当たったら出さない。
 *
 * 材料が本物でも、形だけで読む気は削がれる。ユーザーが「ウンザリする」と名指した公開記事は、
 * 太字が 110字に1つ・見出しが 475字に1つ・うち9個が「課題：」の形の役割ラベルだった。
 * 材料の側には問題が無く、削られたのは形だけ。
 *
 * 下の閾値は手で決めた値で、比べて測ってはいない。根拠は「この密度は嫌われる」と
 * 分かっている1点(n=1)であって、境目がどこかは分かっていない。上限いっぱい(1200字)の下書きに対して
 * 太字4つ・見出し3つが通る値にした。厳しすぎたら緩める。
 *
 * 太字を数える理由: 太字は「ここを見ろ」の合図なので、半分の段落に付くと合図でなくなる。
 * 目は引かれ続けるのに、引かれた先に順位が無い。減らすのではなく、1つに絞る。
 *
 * 見出しの密度は記事の型を跨げない。上から読ませる文章では切れ目の数だが、
 * 手法を並べて引かせる文章では索引の項目数で、多いほど引きやすい(実測した3本目は
 * 399字に1つ = 3本中いちばん密なのに読みづらくない)。ここが当たるのは前者だけ。
 * 下書きは1本1話・1200字なので後者の型にはならず、いまは分けていない。
 */
export function findShape(body: string): string[] {
  const hit: string[] = []
  const len = body.replace(/\s/g, "").length

  const bold = (body.match(/\*\*[^*\n]+\*\*/g) ?? []).length
  const boldMax = Math.max(2, Math.floor(len / 300))
  if (bold > boldMax)
    hit.push(
      `太字が ${bold} 箇所ある(本文 ${len}字に対して ${boldMax} まで)。` +
        "**いちばん強い1文だけ**に残して他は素の文に戻す。合図が多いと合図でなくなる",
    )

  const heads = [...body.matchAll(HEAD_LINE)].map((m) => m[1] ?? "")
  const headMax = Math.max(2, Math.floor(len / 400))
  if (heads.length > headMax)
    hit.push(
      `見出しが ${heads.length} 個ある(本文 ${len}字に対して ${headMax} まで)。` +
        "見出しを削るのではなく、**話を1つに絞り直す**。切れ目が多いのは話が複数あるということ",
    )

  for (const h of heads) {
    if (LABELLED_HEAD.test(h))
      hit.push(`見出し「${h}」が中身を名指していない。何が起きたかを見出しにする(役割の札は外す)`)
  }
  return hit
}
