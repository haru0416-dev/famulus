/** 因果でも使う語。**文を締めているときだけ**落とす(「A を外したら B が効く」は残す)。 */
const CLOSER = /(効く|効いた|刺さる|刺さった|効いてくる|強い|大きい)(です|だ|と思う)?[。!!]/g

/**
 * 言い換えを挟む横棒。副題の区切りとしては普通なので、**本文の中だけ**落とす。
 *
 * 一文の途中で言い直しを足す形は、書いた側が一度で決めきれなかった跡になる。
 * 分けて2文にするか、括弧に入れれば済む。
 */
const ASIDE = /—|――/

/**
 * 中身を持たない語が残っていないか見る。**当たったら出さない。**
 *
 * 1本目の下書きは規律を読んだうえで「重要なのは〜」で締めていた。禁止語を文で並べても、
 * 書いている途中の一文までは届かない。届かせるなら、書いたあとに機械で当てる。
 *
 * **文体を整える道具ではない。** ここで落ちるのは、何がどう変わったかを言わずに
 * 肯定だけで閉じた文と、起きたことを言い換えただけの比喩であって、語尾の癖ではない。
 *
 * 題は分けて受ける。副題を横棒で区切るのは題では普通で、本文の中だけが対象になる。
 */
export function findSmells(title: string, body: string): string[] {
  const hit = new Set<string>()
  const both = `${title}\n${body}`
  for (const w of [...FILLER, ...VERDICT, ...FIGURE]) if (both.includes(w)) hit.add(w)
  for (const m of both.matchAll(CLOSER)) hit.add(m[0])
  const aside = ASIDE.exec(body)
  if (aside) hit.add(aside[0])
  return [...hit]
}

/** 節の役割を宣言するだけの見出し。中身を名指していないので、読む側は開く前から知っている。 */
const ROLE_HEADS: readonly string[] = [
  "はじめに",
  "まとめ",
  "おわりに",
  "さいごに",
  "最後に",
  "結論",
  "背景",
  "概要",
  "前提",
  "目的",
  "動機",
  "きっかけ",
  "キッカケ",
  "経緯",
  "考察",
  "手順",
  "方法",
  "余談",
  "補足",
  "おまけ",
  "参考",
  "関連記事",
  "注意点",
  "見立て",
  "測っていないこと",
]

/**
 * 「課題：」「実験：」のように、見出しの頭に役割の札を貼る形。中身の側は札の後ろに退く。
 * 数字始まりと `//` 続きは外す — 時刻(18:00)と URL を札と読み違えるため。
 */
const LABELLED_HEAD = /^[^\s:：#0-9０-９]{1,6}[：:](?!\/)/

/** 見出し行の中身。`#` の数は問わない。 */
const HEAD_LINE = /^\s{0,3}#{1,6}\s+(.+?)\s*$/gm

/**
 * 中身ではなく**並べ方**のほうを見る。当たったら出さない。
 *
 * 材料が本物でも、形だけで読む気は削がれる。ユーザーが「ウンザリする」と名指した公開記事は、
 * 太字が 110字に1つ・見出しが 475字に1つ・うち9個が「課題：」の形の役割札だった。
 * 材料の側には問題が無く、削られたのは形だけ(docs/adr/0006)。
 *
 * **下の閾値は手で決めた値で、比べて測ってはいない。** 根拠は「この密度は嫌われる」と
 * 分かっている1点(n=1)であって、境目がどこかは分かっていない。上限いっぱい(1200字)の下書きに対して
 * 太字4つ・見出し3つが通る値にした。厳しすぎたら緩める。
 *
 * 太字を数える理由: 太字は「ここを見ろ」の合図なので、半分の段落に付くと合図でなくなる。
 * 目は引かれ続けるのに、引かれた先に順位が無い。**減らすのではなく、1つに絞る。**
 *
 * **見出しの密度は記事の型を跨げない。** 上から読ませる文章では切れ目の数だが、
 * 手法を並べて引かせる文章では索引の項目数で、多いほど引きやすい(実測した3本目は
 * 399字に1つ = 3本中いちばん密なのに読みづらくない)。ここが当たるのは前者だけ。
 * 下書きは1本1話・1200字なので後者の型にはならず、いまは分けていない。
 */
export function findShape(body: string): string[] {
  const hit: string[] = []
  const len = body.replace(/\s/g, "").length

  const bold = (body.match(/\*\*[^*\n]+\*\*/g) ?? []).length
  const boldMax = Math.max(2, Math.floor(len / 300))
  if (bold > boldMax)
    hit.push(
      `太字が ${bold} 箇所ある(本文 ${len}字に対して ${boldMax} まで)。` +
        "**いちばん強い1文だけ**に残して他は素の文に戻す。合図が多いと合図でなくなる",
    )

  const heads = [...body.matchAll(HEAD_LINE)].map((m) => m[1] ?? "")
  const headMax = Math.max(2, Math.floor(len / 400))
  if (heads.length > headMax)
    hit.push(
      `見出しが ${heads.length} 個ある(本文 ${len}字に対して ${headMax} まで)。` +
        "見出しを削るのではなく、**話を1つに絞り直す**。切れ目が多いのは話が複数あるということ",
    )

  for (const h of heads) {
    const bare = h.replace(/[\s*#0-9０-９.、。:：－ー–—①-⑳]/g, "")
    if (ROLE_HEADS.includes(bare) || LABELLED_HEAD.test(h))
      hit.push(`見出し「${h}」が中身を名指していない。何が起きたかを見出しにする(役割の札は外す)`)
  }
  return hit
}
