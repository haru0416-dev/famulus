/**
 * 外に名前で出す文の規律。**下書きを作る回にだけ instruction へ足す。**
 *
 * CONDUCT(持ち主に対して何を書いてよいか)とも STYLE(同じ内容をどう並べるか)とも層が違う。
 * ここは「読者に対して何を主張してよいか」で、外に出る文にしか効かない。
 * 毎ターン載せると、下書きを書かない回のぶんだけ枠を食う。
 *
 * **「AI っぽい」の正体は文体ではない。** 他人の主張の要約だけで出来ていて、
 * 書いた本人が測った数字が1つも入っていないこと。そこを直さずに語尾を変えても、
 * 読む側から見れば同じものになる。だから材料の側を縛る。
 *
 * 出典は ~/.claude/skills/jissoku-writing の §1〜§4(§5 は STYLE 側に入っている)。
 */

/** 下書きの体裁。Zenn の記事を想定した長さ。 */
export const DRAFT_TARGET = "1500〜3000字"

/** 連絡先の形。**伏せる余地が無い**もの — 一度出れば取り消せない。 */
const CONTACT: readonly RegExp[] = [
  /[\w.+-]+@[\w-]+\.[\w.-]+/g,
  /0\d{1,4}-\d{1,4}-\d{3,4}/g,
  /https?:\/\/[^\s)）」]+/g,
]

/** 一致とみなす長さ。日本語でこれだけ続けて偶然重なることはほぼ無い。 */
const MIN_SHARED = 8

export const DRAFTING = `## 外に出す文の規律

**材料は自分が測ったものに限る。** 台帳にある実際の走行記録・失敗・数字だけで書く。
読んだ記事や他人の発表は、自分の測定を置く位置を示すためだけに引く。
**要約を本文にしない** — それは誰でも書けるし、誰が書いても同じものになる。
書ける材料が無いなら書かない。無理に1本にするより、材料が溜まるまで待つほうがよい。

**限界を先に書く。** 本文より前に、その主張が言えない範囲を並べる。
- 観測か操作か(条件を変えて比べたのか、たまたま起きたのを見ただけか)
- n はいくつか。1回なら「1回」と書く
- 条件がひとつしか無いなら「他の条件では確かめていない」と書く
- バージョン・日付・コミット
ここで否定した主張は本文から落とす。**先に書くのは、後から足すと甘くなるから。**

**評価語で締めない。** 書いた文を「X によって Y が Z した」に展開できるか見る。
何が・どの対象で・どう変わったかを言えないなら、その一文は主張ごと落とす。
締めに使わない語: 効く / 刺さる / 重要 / 本質的 / 決定的 / 強い / 劇的に / 圧倒的に / 大幅に。
因果として使うのは構わない(「A を外したら B が 0/8 から 8/8 になった」)。

**測ったことと見立てを分ける。** 測ったなら数値と n と条件。推測なら推測と書く。
どちらか言えない文は落とす。結果と、その結果が何を意味するかも分ける。

**数字の書き方。** 比率だけを書かない(8/8 は書く、100% とだけは書かない)。
粒度の違う指標を経路をまたいで比べない。自己申告を測定として扱わない
— エージェントの報告文ではなく、実行の痕跡か成果物の差分で採る。

**都合の悪い結果を先に出す。** 効かなかったもの・壊れたもの・測り方を間違えた記録を、
効いたものより前に置く。撤回した主張とその理由は残す価値がある。

**断定の幅を絞る。** 「唯一の正しい方法」「これさえ知れば」は書かない。
「この環境では」「n=1 の範囲では」と条件を付ける。後から条件が違ったときに撤回できる形にする。

**題材は伏せて、仕組みだけ出す。** 台帳の実測を材料にすると、持ち主の生活がそのまま混ざる
— 予約先の名前、日時、連絡先、金額。**公開できるのは仕組みと数字であって、何の件かではない。**
店名・医院名・人名・住所・メール・電話は書かない。日付は経過日数に、
具体的な用件は「予約変更の依頼(提案A)」のように伏せた呼び名に置き換える。
提案の id(8桁)と、経過時間・件数・回数はそのまま出してよい — それ単体では誰の何かが分からない。
**伏せると記事が成立しないなら、その題材では書かない。**

長さは ${DRAFT_TARGET}。見出しは2〜4個。冒頭で何を測ったかを1段落で言い切り、
前置きを置かない(「本稿では」「近年〜が注目されている」から始めない)。`

/**
 * 非公開の値が本文に漏れていないか見る。**当たったら出さない。**
 *
 * 規律に書くだけでは足りない。1本目の下書きには医院名も予約日時も入っていて、
 * 規律を読んだうえで通っている。名前が付いて外に出るものは、文で頼むだけにしない。
 *
 * **誤検出しないものだけを止める。** 疑わしいものまで弾くと一度も出せなくなり、
 * 出せない仕組みは外されて、そのとき一緒にこの検査も消える。見るのは2つだけ:
 *   - 非公開の確定値に書かれている連絡先そのもの(メール・電話・URL)
 *   - 非公開の確定値と ${MIN_SHARED} 文字以上そのまま一致する断片
 * 日本語で ${MIN_SHARED} 文字が偶然一致することはほぼ無い。逆に「歯科医院」程度の
 * 一般語は当たらない — そこは規律の側に任せる。
 */
export function findLeaks(body: string, secrets: readonly string[]): string[] {
  const hit = new Set<string>()
  for (const s of secrets) {
    for (const re of CONTACT) {
      for (const m of s.matchAll(re)) if (body.includes(m[0])) hit.add(m[0])
    }
    // 当たった窓は隣と重なる。**繋いで一番長いところだけ返す** — 断片を並べて突き返すと、
    // 書き直す側はどこを消せばいいのか分からない。
    let i = 0
    while (i + MIN_SHARED <= s.length) {
      if (!body.includes(s.slice(i, i + MIN_SHARED))) {
        i++
        continue
      }
      let end = i + MIN_SHARED
      while (end < s.length && body.includes(s.slice(i, end + 1))) end++
      hit.add(s.slice(i, end))
      i = end - MIN_SHARED + 2
    }
  }
  // 長いものに含まれる短いものは落とす(連絡先と地の文の一致が二重に出る)。
  const all = [...hit]
  return all.filter((a) => !all.some((b) => b !== a && b.includes(a)))
}

/** 使い道が無い定型。因果としても評価としても中身を持たないので、どこに出ても落とす。 */
const FILLER: readonly string[] = [
  "本稿では",
  "以上のことから",
  "このように",
  "まとめると",
  "いかがでしょうか",
  "ではないでしょうか",
  "と言えるでしょう",
  "と思われます",
  "と考えられます",
  "ていきます",
  "さまざまな",
  "様々な",
  "注目されている",
]

/** 評価そのもの。因果で使う余地が無いので、位置を問わず落とす。 */
const VERDICT: readonly string[] = ["重要", "本質的", "決定的", "劇的", "圧倒的", "大幅"]

/** 因果でも使う語。**文を締めているときだけ**落とす(「A を外したら B が効く」は残す)。 */
const CLOSER = /(効く|効いた|刺さる|刺さった|効いてくる|強い|大きい)(です|だ|と思う)?[。!!]/g

/**
 * 中身を持たない語が残っていないか見る。**当たったら出さない。**
 *
 * 1本目の下書きは規律を読んだうえで「重要なのは〜」で締めていた。禁止語を文で並べても、
 * 書いている途中の一文までは届かない。届かせるなら、書いたあとに機械で当てる。
 *
 * **文体を整える道具ではない。** ここで落ちるのは、何がどう変わったかを言わずに
 * 肯定だけで閉じた文であって、語尾の癖ではない。
 */
export function findSmells(body: string): string[] {
  const hit = new Set<string>()
  for (const w of [...FILLER, ...VERDICT]) if (body.includes(w)) hit.add(w)
  for (const m of body.matchAll(CLOSER)) hit.add(m[0])
  return [...hit]
}
