/** 因果でも使う語。文を締めているときだけ落とす(「A を外したら B が効く」は残す)。 */
const CLOSER = /(効く|効いた|刺さる|刺さった|効いてくる|強い|大きい)(です|だ|と思う)?[。!!]/g

/**
 * 言い換えを挟む横棒。副題の区切りとしては普通なので、本文の中だけ落とす。
 *
 * 一文の途中で言い直しを足す形は、書いた側が一度で決めきれなかった跡になる。
 * 分けて2文にするか、括弧に入れれば済む。
 */
const ASIDE = /—|――/

/**
 * 中身を持たない語が残っていないか見る。当たったら出さない。
 *
 * 1本目の下書きは規律を読んだうえで「重要なのは〜」で締めていた。禁止語を文で並べても、
 * 書いている途中の一文までは届かない。届かせるなら、書いたあとに機械で当てる。
 *
 * 文体を整える道具ではない。ここで落ちるのは、何がどう変わったかを言わずに
 * 肯定だけで閉じた文と、起きたことを言い換えただけの比喩であって、語尾の癖ではない。
 *
 * 題は分けて受ける。副題を横棒で区切るのは題では普通で、本文の中だけが対象になる。
 */
export function findSmells(title: string, body: string): string[] {
  const hit = new Set<string>()
  const both = `${title}\n${body}`
  for (const w of [...FILLER, ...VERDICT, ...FIGURE]) if (both.includes(w)) hit.add(w)
  for (const m of both.matchAll(CLOSER)) hit.add(m[0])
  const aside = ASIDE.exec(body)
  if (aside) hit.add(aside[0])
  return [...hit]
}

/** 通知と返信に当てる。`findSmells` だと横棒や締めの評価語まで当たり、用のある通知が出せない。 */
export function findFigures(text: string): string[] {
  return FIGURE.filter((w) => text.includes(w))
}

