/**
 * 外に名前で出す文の規律。**下書きを作る回にだけ instruction へ足す。**
 *
 * CONDUCT(ユーザーに対して何を書いてよいか)とも STYLE(同じ内容をどう並べるか)とも層が違う。
 * ここは「読者に対して何を主張してよいか」で、外に出る文にしか効かない。
 * 毎ターン載せると、下書きを書かない回のぶんだけ枠を食う。
 *
 * **「AI っぽい」の正体は文体ではない。** 他人の主張の要約だけで出来ていて、
 * 書いた本人が測った数字が1つも入っていないこと。そこを直さずに語尾を変えても、
 * 読む側から見れば同じものになる。だから材料の側を縛る。
 *
 * 出典は ~/.claude/skills/jissoku-writing の §1〜§4(§5 は STYLE 側に入っている)。
 *
 * **どれが裏の取れた規則で、どれが手癖かを分けておく。** 認知負荷の側を当たった結果:
 *
 * 裏が取れたもの — 面白いが本題に要らない材料(seductive details)は学習成績を下げる。
 *   最新のメタ分析で g = -0.16(理解 -0.19 / 再生 -0.17 / 転移 -0.12、50研究177効果量、
 *   Cheng et al. 2026, Educational Psychology Review 38:28)。**小さい効果**である点は
 *   そのまま受け取る。旧推定は g = -0.33(Sundararajan & Adesope 2020)だが、
 *   同一研究の効果量を独立として扱ったとして 2026 の側から方法上の批判が付いている。
 *   機構は余分な負荷(extraneous load)の増加のみが媒介し、内在・生成の負荷は媒介しない。
 *   読み手が「関係がある」と判断した材料ほど処理を吸い、その配分が成績低下を予測する
 *   (Kienitz, Krebs & Eitel 2023, Instructional Science, N=248)。
 *   置く位置は早いほど害が大きい(Harp & Mayer 1998, J. Educ. Psychol. 90, 414-434)。
 *
 * 否定されたもの — **見出しの数を絞る方向は間違い。** 組織を示す手がかりは保持・転移とも
 *   上げ、認知負荷を下げる(Schneider, Beege, Nebel & Rey 2018, Educational Research Review
 *   23, 1-24、103研究 N=12,201)。同メタ分析では事前知識は有意な調整変数ではなかった
 *   ので、「読者は玄人だから見出しは要らない」も成り立たない。数の上限は撤回した。
 *   残したのは、中身を名指さない見出し(役割の宣言)を落とすことだけ。
 *
 * 裏が無いもの — 1200字の上限と「1本1話」。手で決めた値で、比べて測ってはいない。
 *
 * **読む負担の側は当たらなかった。** AI が書いた文は読みにくい、という結果は日本語でも
 * 技術文書でも見つからない(見つかるのは英語の実験室課題と EFL 教材のみ)。当たったのは
 * 受け取られ方の側で、条件がそのまま合う材料が1つある: Zenn は 2025-06-05 の規約改定で、
 * どの要素が読者のストレスになるかを5ヶ月かけて調べた結果として
 * 「著者自身の経験や考察が含まれない記事の乱造」を名指した(生成AI の利用自体は禁止していない)。
 * 日本語・技術記事・読者は実務者、という条件が揃った唯一の例で、
 * 上の「材料は自分が測ったものに限る」を外から支持する。
 * **直す順は、語尾より材料が先。**
 */

