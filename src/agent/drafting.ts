/**
 * 本文の長さ。測った過程を全部書くと、書いた側の作業記録になる。読む側が要るのは、
 * 何が起きてそれが自分に当てはまるかどうかで、そこまでに何日かかったかではない。
 * 上限は機械で切る — 「短く」と書くだけでは、毎回2000字が出てくる。
 */
export const DRAFT_MAX = 1200
const DRAFT_MIN = 400
const DRAFT_TARGET = `${DRAFT_MIN}〜${DRAFT_MAX}字`

/** 連絡先の形。伏せる余地が無いもの — 一度出れば取り消せない。 */
const CONTACT: readonly RegExp[] = [
  /[\w.+-]+@[\w-]+\.[\w.-]+/g,
  /0\d{1,4}-\d{1,4}-\d{3,4}/g,
  /https?:\/\/[^\s)）」]+/g,
]

/** 一致とみなす長さ。日本語でこれだけ続けて偶然重なることはほぼ無い。 */
const MIN_SHARED = 8

